#!/usr/bin/env bash
# Enforces the mechanical parts of rules.md. No third-party dependencies.
set -euo pipefail

fail() {
  echo "::error::$1"
  exit 1
}

REQUIRED_SECTIONS=(
  "## Org-wide rules"
  "## Project rules"
  "## Git and PR rules"
  "## Enforcement"
)

[[ -f rules.md ]] || fail "rules.md is missing from the repository root"

for section in "${REQUIRED_SECTIONS[@]}"; do
  grep -qF -- "$section" rules.md || fail "rules.md is missing required section: $section"
done

if git ls-files | grep -qiE '(^|/)\.env($|\.)'; then
  echo "::error::Tracked .env-style file found:"
  git ls-files | grep -iE '(^|/)\.env($|\.)' || true
  exit 1
fi

EXCLUDES=(':(exclude)rules.md' ':(exclude)scripts/check_repo_rules.sh')
SECRET_PATTERNS=(
  'gh[pousr]_[A-Za-z0-9]{20,}'
  'github_pat_[A-Za-z0-9_]{20,}'
  'AKIA[0-9A-Z]{16}'
  '-----BEGIN (RSA|EC|OPENSSH|DSA|PGP) PRIVATE KEY-----'
  'sk-[A-Za-z0-9]{20,}'
  'xox[baprs]-[A-Za-z0-9-]{10,}'
)

for pattern in "${SECRET_PATTERNS[@]}"; do
  set +e
  matches="$(git grep -nIE -e "$pattern" -- . "${EXCLUDES[@]}" 2>/dev/null)"
  status=$?
  set -e
  [[ $status -le 1 ]] || fail "secret scan failed for /$pattern/ (git grep exit $status)"
  if [[ -n "$matches" ]]; then
    echo "::error::Possible secret matching /$pattern/ found in tracked files:"
    echo "$matches"
    exit 1
  fi
done

base="${PR_BASE:-}"
zero="0000000000000000000000000000000000000000"
if [[ -n "$base" && "$base" != "$zero" ]]; then
  range="${base}..HEAD"
else
  range="HEAD"
fi

messages="$(git log "$range" --format=%B 2>/dev/null || true)"
TRAILER_PATTERN='co-authored-by:|generated by (claude|opencode|chatgpt|copilot|gemini)|ai-attribution'
if printf '%s' "$messages" | grep -qiE "$TRAILER_PATTERN"; then
  echo "::error::Commit messages must not contain co-author or AI-attribution trailers:"
  printf '%s\n' "$messages" | grep -iE "$TRAILER_PATTERN" || true
  exit 1
fi

echo "Repo rules check passed"
